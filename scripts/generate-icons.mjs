#!/usr/bin/env node
/**
 * Toolbox imports lucide icons by name at runtime. Importing the whole package
 * costs ~900 kB, so this script scans the source for every icon name actually
 * referenced and writes an explicit map containing only those.
 *
 * Run it after adding tools:  node scripts/generate-icons.mjs
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as lucide from 'lucide-react';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'src');
const outFile = join(srcDir, 'components/ui/icons.ts');

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (/\.(tsx?|ts)$/.test(entry.name) && entry.name !== 'icons.ts') yield full;
  }
}

// Icon names are referenced as plain strings, sometimes inside ternaries or
// computed maps, so a narrow pattern list would silently miss one and render a
// blank square. Instead collect every quoted PascalCase token in the source and
// keep the ones lucide actually exports — over-including costs a few bytes,
// missing one is a visible defect.
const TOKEN = /['"`]([A-Z][A-Za-z0-9]{1,40})['"`]/g;

const found = new Set([
  // Always present in the chrome, even if a scan misses them.
  'Box', 'House', 'Star', 'History', 'Settings', 'Search', 'ListChecks', 'X', 'Check',
  'ChevronDown', 'ChevronRight', 'ArrowRight', 'Copy', 'Loader2', 'Square', 'Play',
  'Info', 'CircleCheck', 'CircleAlert', 'TriangleAlert', 'CircleSlash', 'Inbox',
  'Upload', 'Download', 'Folder', 'FolderOpen', 'FolderInput', 'FolderOutput', 'Plus',
  'Trash2', 'GripVertical', 'File', 'FileText', 'FileCode2', 'FileType', 'FileArchive',
  'FileCheck2', 'FileWarning', 'Image', 'Video', 'AudioLines', 'QrCode', 'PenTool',
  'Type', 'Code2', 'Sparkles', 'Clock', 'Calculator', 'Clipboard', 'ScanText', 'Repeat',
  'ExternalLink', 'RotateCcw', 'RefreshCw', 'Terminal', 'ShieldCheck', 'TrendingUp',
  'Sun', 'Moon', 'Monitor', 'Command', 'MousePointerClick', 'Minus', 'Dot', 'SearchX',
  'ClipboardPaste', 'Braces', 'Images', 'Music',
]);

for await (const file of walk(srcDir)) {
  const text = await readFile(file, 'utf8');
  for (const match of text.matchAll(TOKEN)) found.add(match[1]);
}

const valid = [...found].filter((name) => lucide[name] != null).sort();
const missing = [...found].filter((name) => lucide[name] == null).sort();

// A few lucide icons share a name with a JavaScript global (Infinity, NaN…).
// Importing them bare would shadow it, so they are aliased.
const RESERVED = new Set(['Infinity', 'NaN', 'Object', 'Function', 'Array', 'Number', 'String', 'Boolean', 'Symbol', 'Map', 'Set', 'Date', 'Error', 'Proxy']);
const alias = (name) => (RESERVED.has(name) ? `Icon${name}` : name);

const body = `// GENERATED by scripts/generate-icons.mjs — do not edit by hand.
// Only the icons Toolbox actually references are bundled, keeping the startup
// chunk small. Re-run the script after adding tools that use new icon names.
import {
${valid.map((n) => (RESERVED.has(n) ? `  ${n} as ${alias(n)},` : `  ${n},`)).join('\n')}
  type LucideIcon,
} from 'lucide-react';

export const ICONS: Record<string, LucideIcon> = {
${valid.map((n) => (RESERVED.has(n) ? `  ${n}: ${alias(n)},` : `  ${n},`)).join('\n')}
};

export type { LucideIcon };
`;

await writeFile(outFile, body, 'utf8');
console.log(`Wrote ${valid.length} icons to src/components/ui/icons.ts`);
if (missing.length && process.env.VERBOSE) console.warn(`Non-icon tokens ignored: ${missing.length}`);
